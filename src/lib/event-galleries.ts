export const EVENT_GALLERY_YEARS = ["2025-26", "2026-27"] as const;
type EventGalleryYearName = (typeof EVENT_GALLERY_YEARS)[number];

type EventGalleryYear = {
  folderUrl: string;
  photos: EventGalleryPhoto[];
};

type EventGalleryPhoto = {
  src: string;
  thumbnail: string;
};

function createPhoto(folderUrl: string, imageName: string): EventGalleryPhoto {
  const webpName = imageName.replace(/\.[^.]+$/, ".webp");
  const encodedWebpName = encodeURIComponent(webpName);

  return {
    src: `${folderUrl}optimized/${encodedWebpName}`,
    thumbnail: `${folderUrl}thumbnails/${encodedWebpName}`,
  };
}

function createEventGallery(
  slug: string,
  imageNames: Partial<Record<EventGalleryYearName, string[]>> = {},
  imageFolder = slug,
): Record<EventGalleryYearName, EventGalleryYear> {
  const createYear = (year: EventGalleryYearName): EventGalleryYear => {
    const folderUrl = `/images/events/${imageFolder}/${year}/`;
    return {
      folderUrl,
      photos: (imageNames[year] ?? []).map((imageName) => createPhoto(folderUrl, imageName)),
    };
  };

  return {
    "2025-26": createYear("2025-26"),
    "2026-27": createYear("2026-27"),
  };
}

